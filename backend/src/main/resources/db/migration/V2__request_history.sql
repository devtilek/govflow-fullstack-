CREATE TABLE request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_requests(id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT history_action CHECK (action IN ('CREATED', 'STATUS_CHANGED', 'IMPORTED')),
    CONSTRAINT history_from_status CHECK (from_status IN ('NEW', 'IN_PROGRESS', 'RESOLVED')),
    CONSTRAINT history_to_status CHECK (to_status IN ('NEW', 'IN_PROGRESS', 'RESOLVED'))
);
CREATE INDEX idx_history_request_time ON request_history (request_id, occurred_at, id);

